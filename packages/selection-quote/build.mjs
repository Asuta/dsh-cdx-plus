/**
 * Build client.js from src/core.mjs + src/ui.js.
 *
 * DSH loads a client plugin as one file that hands a factory to
 * window.__ModuleLoader__. The factory body is the same code the tests drive,
 * so the shipped bundle and the tested source cannot drift: core is inlined
 * with its export keywords dropped, and ui contributes the rest, ending in the
 * value the factory returns.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const read = (name) => readFileSync(join(here, name), 'utf8')

const pkg = JSON.parse(read('package.json'))
const core = read('src/core.mjs')
const ui = read('src/ui.js')

const flat = core
  .split('\n')
  .map((line) => (line.startsWith('export ') ? line.slice(7) : line))
  .join('\n')

const banner = [
  '/* ' + pkg.name + ' - generated by build.mjs from src/core.mjs + src/ui.js. Do not edit. */',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory(require) {',
  "    const react = require('react')",
  ''
].join('\n')

const footer = ['  }', '})', ''].join('\n')

writeFileSync(join(here, 'client.js'), banner + flat + '\n' + ui + '\n' + footer)
process.stdout.write('client.js written\n')
